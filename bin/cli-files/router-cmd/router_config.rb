#!/usr/bin/env ruby

require "yaml"
require "fileutils"
require_relative "../edge/edge"

module AppCLI
  module Services
    # Renders move-router's Traefik config (port of ISMS CLI V2's RouterConfig).
    # File provider only: the router never sees the Docker socket and no
    # container carries labels — routes live here, in one file the CLI owns.
    # Built as hashes and YAML-dumped so the HostRegexp escaping can't break.
    class RouterConfig
      ZONE = Edge::DOMAIN
      APP_UPSTREAM = ENV.fetch("MOVE_APP_UPSTREAM", "http://#{APP_CONTAINER_BASE}-dev:9292").freeze
      # One lowercase label — exactly what the single-level wildcard cert covers.
      TENANT_RULE = "HostRegexp(`^[a-z0-9-]+\\.#{ZONE.gsub(".", "\\.")}$`)".freeze
      HEADER = "# Generated by `bin/cli router` - edits are overwritten.\n".freeze
      LEAF_CERT = "/certs/#{ZONE}.pem".freeze
      LEAF_KEY = "/certs/#{ZONE}-key.pem".freeze

      def initialize(dir: Edge::ROUTER_DIR)
        @dir = dir
      end

      def write!
        FileUtils.mkdir_p(File.join(@dir, "dynamic"))
        write(File.join(@dir, "traefik.yml"), static_config)
        write(File.join(@dir, "dynamic", "routes.yml"), routes_config)
      end

      def static_config
        {
          "global" => { "checkNewVersion" => false, "sendAnonymousUsage" => false },
          "log" => { "level" => "INFO" },
          "entryPoints" => {
            "web" => { "address" => ":80", "http" => { "redirections" => {
              "entryPoint" => { "to" => "websecure", "scheme" => "https" }
            } } },
            "websecure" => { "address" => ":443" }
          },
          "providers" => { "file" => { "directory" => "/etc/traefik/dynamic", "watch" => true } },
          "api" => {},
          "ping" => {}
        }
      end

      def routes_config
        {
          "http" => { "routers" => routers, "middlewares" => middlewares, "services" => services },
          "tls" => {
            "certificates" => [cert_pair],
            "stores" => { "default" => { "defaultCertificate" => cert_pair } }
          }
        }
      end

      # The tenant catch-all's priority 1 is load-bearing: Traefik's default
      # priority is rule LENGTH, and the regexp is longer than every Host() rule.
      def routers
        {
          "app" => router("Host(`#{APP_NAME}.#{ZONE}`)", "app"),
          "mail" => router("Host(`mail.#{ZONE}`)", "mail"),
          "storage" => router("Host(`storage.#{ZONE}`)", "storage"),
          "bucket" => router("Host(`bucket.#{ZONE}`)", "bucket").merge("middlewares" => ["bucket-prefix"]),
          "dashboard" => router("Host(`router.#{ZONE}`)", "api@internal"),
          "tenants" => router(TENANT_RULE, "app").merge("priority" => 1)
        }
      end

      # bucket.<zone>/<key> → the path-style S3 gateway at /<bucket>/<key>.
      def middlewares
        { "bucket-prefix" => { "addPrefix" => { "prefix" => "/#{APP_NAME}" } } }
      end

      def services
        {
          "app" => balancer(APP_UPSTREAM),
          "mail" => balancer("http://mail:1080"),
          "storage" => balancer("http://seaweedfs:8888"),
          "bucket" => balancer("http://seaweedfs:8333")
        }
      end

      private

      def router(rule, service)
        { "rule" => rule, "entryPoints" => ["websecure"], "service" => service, "tls" => {} }
      end

      def balancer(url) = { "loadBalancer" => { "servers" => [{ "url" => url }] } }

      # A fresh hash per call, or YAML.dump emits anchors/aliases.
      def cert_pair = { "certFile" => LEAF_CERT, "keyFile" => LEAF_KEY }

      def write(path, config)
        tmp = "#{path}.tmp"
        File.write(tmp, HEADER + YAML.dump(config))
        File.rename(tmp, path)
      end
    end
  end
end
