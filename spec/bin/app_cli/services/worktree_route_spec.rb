require "spec_helper"
require "tmpdir"
require_relative "../../../../bin/cli-files/app-cmd/worktree_app"
require_relative "../../../../bin/cli-files/router-cmd/worktree_route"

RSpec.describe AppCLI::Services::WorktreeRoute do
  subject(:route) { described_class.new(app: app, dir: router_dir, certs: certs) }

  let(:tmp) { Dir.mktmpdir("wtroute") }
  let(:router_dir) { File.join(tmp, "router") }
  let(:certs) { AppCLI::Services::CertificateStore.new(dir: File.join(tmp, "certs")) }
  let(:app) { AppCLI::Services::WorktreeApp.new("w1") }
  let(:written) { YAML.safe_load_file(route.path) }

  after { FileUtils.remove_entry(tmp) }

  it "writes its own file in the watched directory, next to main's routes.yml" do
    route.write!
    expect(route.path).to eq(File.join(router_dir, "dynamic", "wt-w1.yml"))
    expect(File.read(route.path)).to start_with("# Generated by `bin/cli router`")
  end

  it "routes the worktree apex and its org hosts to its container" do
    route.write!
    router = written.dig("http", "routers", "wt-w1")
    expect(router).to include("rule" => "HostRegexp(`^[a-z0-9-]+\\.w1\\.wt\\.move-easy\\.docker$`)",
                              "entryPoints" => ["websecure"], "service" => "wt-w1")
    expect(written.dig("http", "services", "wt-w1", "loadBalancer", "servers"))
      .to eq([{ "url" => "http://move-app-wt-w1:9292" }])
  end

  it "matches one label under the worktree zone only" do
    pattern = Regexp.new(route.rule[/`\^(.+)\$`/, 1].then { |body| "\\A#{body}\\z" })
    expect(pattern).to match("move.w1.wt.move-easy.docker")
    expect(pattern).to match("acme.w1.wt.move-easy.docker")
    expect(pattern).not_to match("move.move-easy.docker")
    expect(pattern).not_to match("a.b.w1.wt.move-easy.docker")
    expect(pattern).not_to match("acme.w2.wt.move-easy.docker")
  end

  it "serves a zone leaf the router can read at /certs" do
    route.write!
    expect(written.dig("tls", "certificates"))
      .to eq([{ "certFile" => "/certs/wt-w1.wt.move-easy.docker.pem",
                "keyFile" => "/certs/wt-w1.wt.move-easy.docker-key.pem" }])
    expect(File).to exist(certs.zone_cert_path(app.zone))
  end

  it "removes the file and the leaf on remove!, leaving main's leaf" do
    route.write!
    route.remove!
    expect(File).not_to exist(route.path)
    expect(Dir.children(certs.leaf_dir)).to contain_exactly("move-easy.docker.pem", "move-easy.docker-key.pem")
  end

  it "is a no-op to remove twice" do
    expect { 2.times { route.remove! } }.not_to raise_error
  end
end
